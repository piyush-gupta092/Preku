/** `ctrl+alt+p` → `Ctrl+Alt+P` */
export function formatShortcut(shortcut: string): string {
  return shortcut
    .split("+")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("+");
}

